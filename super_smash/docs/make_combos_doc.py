"""Write docs/COMBOS.md from smash_rl/combos.py and smash_rl/rewards.py.

Run from super_smash/:  .venv/bin/python docs/make_combos_doc.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from smash_rl.combos import COMBOS, ComboWeights  # noqa: E402
from smash_rl.rewards import REPEAT_LIMITS, RewardWeights  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "COMBOS.md")


def main():
    w, cw = RewardWeights(), ComboWeights()
    lines = []
    add = lines.append
    add("# Reward v2: combos, spam and defence\n")
    add("Reward used to train MK3 and MK4 (`league.py`, `SmashEnv(reward=\"v2\")`). The code is")
    add("`smash_rl/rewards.py` (all terms) and `smash_rl/combos.py` (combo lists and tracker).")
    add("This page is generated by `docs/make_combos_doc.py`; rerun it after changing either file.\n")
    add("## Why it changed\n")
    add("MK1 / MK2 (reward v1 plus a whiff penalty on A attacks only) learned to camp: Fox fired")
    add("lasers all game (specials were never penalised, and lasers deal damage without being punished)")
    add("while the other agent stood still or kept dodging, because taking no damage scores better than")
    add("risking an approach. v2 makes knockouts the dominant reward, makes every attack that misses")
    add("cost something, punishes using one move over and over, and punishes going a long time without")
    add("hurting anyone.\n")
    add("## Terms (per player, per frame)\n")
    add("| Term | Weight | When |")
    add("|---|---|---|")
    add(f"| Knockout | +{w.ko} / -{w.ko} | Opponent loses a stock / you lose one (the largest term by far) |")
    add(f"| Damage | ±{w.damage} per % | Damage dealt minus damage taken |")
    add(f"| Combo step (listed combo) | +{cw.listed_step} x step, from step 2 | Step k >= 2 of a combo from the table below, if it connects and chains (step 1 pays like any hit) |")
    add(f"| Chain hit (any true combo) | +{cw.chain_step} x (hits - 1), at most {cw.max_chain_steps} steps | A hit that lands while the opponent is still stunned, not part of a listed combo |")
    add(f"| Single hit | +{cw.single_hit} | A hit that starts or continues nothing, and every pummel |")
    add(f"| Whiff | -{w.whiff} (smash attack: -{w.smash_whiff}) | An attack (A move or special) ends without touching the opponent or their shield |")
    add(f"| **Smash spam** | -{w.smash_spam} x 2^(n-2), up to -{w.spam_cap} | The n-th forward / up / down smash started within {w.smash_window} frames ({w.smash_window / 60:.0f} s), n >= 2: -0.2, -0.4, -0.8, -1.6, -2.0 |")
    add(f"| **Move spam** | -{w.repeat} x 2^(extra-1), up to -{w.spam_cap} | A move used more than {w.repeat_max} times in your last {w.repeat_window} actions (exceptions below): -0.1, -0.2, -0.4 ... |")
    add(f"| Passive | -{w.passive} per second x opponents alive | No damage dealt for more than {w.passive_grace} frames ({w.passive_grace / 60:.0f} s); Fox and Falco laser hits don't reset this timer |")
    add(f"| **Defence spam** | -{w.defense_repeat} x 2^(extra-1), up to -{w.spam_cap} | A shield, roll, spot dodge or air dodge starts while more than {w.defense_max} of your last {w.repeat_window} actions were defences |")
    add(f"| Shield held | -{w.shield_hold} per second | Shield up for more than {w.shield_grace} frames ({w.shield_grace / 60:.0f} s) in a row |")
    add("")
    add("Every spam penalty doubles with each extra repetition and is capped at one knockout, so")
    add("sustained spam costs more than losing stocks. Exceptions (moves that are normal to use a lot):\n")
    for (char, move), (window, limit) in REPEAT_LIMITS.items():
        add(f"- {char.name} {move}: penalised only past {limit} uses in the last {window} attacks.")
    add("")
    add("Shielding and dodging earn nothing by themselves: the agent has to discover that they")
    add("save it from damage and knockouts. (Earlier versions paid for blocks and dodges, and agents")
    add("learned to farm those rewards instead of fighting.) Overusing them still costs a little.\n")
    add("## How attacks and hits are detected\n")
    add("- **Moves** come from the attacker's action state: jabs, tilts, smashes, aerials, pummel and the")
    add("  four throws map to fixed names. Character-specific action states (id >= 0x155) count as specials")
    add(f"  only if B was pressed in the last {w.b_press_window} frames (they also cover extra jumps, floats, etc.);")
    add("  which one (`neutral_b`, `side_b`, `up_b`, `down_b`) comes from the direction of that B input.")
    add("  Up-B and side-B started off stage are recovery moves and never count as whiffs.")
    add("- **Connects** means the opponent lost percent or a stock while the attack was out. Shield hits")
    add("  count as connecting for the whiff rule but give no combo reward. A special also counts if the")
    add(f"  opponent is hurt within {w.projectile_grace} frames after it ends (lasers and other projectiles).")
    add("  Multi-hit moves count once per use.")
    add("- **True combo (chain):** SmashWiki defines a true combo as a sequence of attacks that keeps the")
    add("  opponent in hitstun; Melee's combo counter tolerates one frame of non-hitstun. Here the opponent")
    add("  counts as stunned while in a damage, tumble, thrown or grabbed action state, and a hit chains if")
    add(f"  the opponent has been out of those states for at most {cw.chain_grace} frames (more lenient than the")
    add(f"  game, so chain throws and regrabs count) and the previous hit was at most {cw.max_gap} frames ago.")
    add("- **Listed combo:** each character has combo sequences (table below). A hit that continues a combo")
    add("  the attacker has been doing (chained, and the right next move) moves it one step forward and pays")
    add("  `listed_step x step` from step 2 (0.2, 0.3, ...); a hit with a combo's first move starts it at")
    add("  step 1, which pays like any other hit, so only continuing a combo is worth more.")
    add("  A whiff, or a hit that doesn't chain, resets it. If no listed combo advances, a chained hit pays")
    add("  the chain reward and anything else pays the single-hit reward.\n")
    add("## Combo lists\n")
    add("Sources: SmashWiki pages [Combo](https://www.ssbwiki.com/Combo), [Chain grab](https://www.ssbwiki.com/Chain_grab)")
    add("and [Fox (SSBM)/Up throw](https://www.ssbwiki.com/Fox_(SSBM)/Up_throw); Smashboards")
    add("[Ganon chaingrabbing guide](https://smashboards.com/threads/the-ganon-chaingrabbing-guide.85582/).")
    add("Combos marked *community* are common Melee knowledge that was not checked against a source;")
    add("whether a combo is true also depends on percent, DI and the opponent's weight, which the")
    add("tracker handles by only paying for hits that actually chain.\n")
    add("| Character | Combo | Moves | Source |")
    add("|---|---|---|---|")
    seen = set()
    for combos in COMBOS.values():
        if id(combos) in seen:
            continue
        seen.add(id(combos))
        names = [c.name for c in COMBOS if COMBOS[c] is combos]
        for combo in combos:
            source = "*community*" if combo.source == "community" else combo.source
            add(f"| {' / '.join(names)} | {combo.name} | {' -> '.join(combo.moves)} | {source} |")
    add("")
    add("Famous combos the move vocabulary can't express exactly (waveshine, wobbling, off-stage edge")
    add("guards like the full Sacred Combo) are still rewarded through the generic chain reward.")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
